#!/usr/bin/env python3
"""Write REPORT.md for a bench/java run from the raw files left by inside.sh.

    report.py <results-dir>
"""
import glob
import json
import os
import re
import statistics
import sys

OUT = sys.argv[1]
CASES = [("small", "Small page (small.html)"), ("medium", "Medium article (medium.html)"),
         ("large", "Large invoice (large.html)"), ("hf-body", "Handbook body (hf-body.html, no header/footer/toc)")]
VARIANTS = [("rust", "wkhtmltopdf-rs CLI"), ("java", "Java, default flags"),
            ("java-tuned", "Java, -XX:TieredStopAtLevel=1 -Xshare:auto"),
            ("java-cds", "Java, tuned + AppCDS archive")]
WARM = [("rust-loop", "wkhtmltopdf-rs CLI, one process per doc"),
        ("rust-inproc", "wkhtmltopdf-rs in-process (`wkhtmltopdf-inproc`)"),
        ("java", "OpenHTMLtoPDF in one JVM (default flags)")]


def kv(path):
    d = {}
    try:
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.rstrip("\n").split("=", 1)
                    d[k] = v
    except OSError:
        pass
    return d


def timev(path):
    """Peak RSS (KiB), user+sys (s), elapsed (s) from a GNU time -v file."""
    try:
        txt = open(path).read()
    except OSError:
        return None
    def num(label):
        m = re.search(re.escape(label) + r":\s*([\d.:]+)", txt)
        return m.group(1) if m else None
    el = num("Elapsed (wall clock) time (h:mm:ss or m:ss)") or "0"
    secs = 0.0
    for part in el.split(":"):
        secs = secs * 60 + float(part)
    return {"rss": int(num("Maximum resident set size (kbytes)") or 0),
            "cpu": float(num("User time (seconds)") or 0) + float(num("System time (seconds)") or 0),
            "user": float(num("User time (seconds)") or 0), "sys": float(num("System time (seconds)") or 0),
            "elapsed": secs, "exit": int(num("Exit status") or 0)}


def jload(path):
    try:
        with open(path) as f:
            txt = f.read().strip()
        try:
            return json.loads(txt)
        except ValueError:
            return json.loads(txt.splitlines()[-1])
    except (OSError, ValueError, IndexError):
        return None


def ms(v):
    if v is None:
        return "n/a"
    return f"{v / 1000:.2f} s" if v >= 1000 else f"{v:.1f} ms"


def mib(kib):
    return f"{kib / 1024:.0f} MiB" if kib else "n/a"


def size(b):
    b = int(b)
    return f"{b / 1024:.1f} KiB"


env = kv(os.path.join(OUT, "env.txt"))
L = []
w = L.append
w("# Benchmark: wkhtmltopdf-rs vs OpenHTMLtoPDF (Java)")
w("")
w(f"Run `{os.path.basename(OUT.rstrip('/'))}`, mode `{env.get('mode', '?')}`. Generated by `bench/java/run.sh`; "
  "see bench/README.md, section \"OpenHTMLtoPDF comparison\", for the methodology.")
w("")
w("## Environment")
w("")
w("| | |")
w("|---|---|")
w(f"| Date (UTC) | {env.get('date_utc', '?')} |")
w(f"| Container | `wkjava:local`, {env.get('uname', '?')}, {env.get('cpus', '?')} vCPU, {env.get('mem_total', '?')} |")
w(f"| Load average at start | {env.get('loadavg', '?')} |")
w(f"| Java | {env.get('java', '?')}; default ergonomics: `{env.get('java_flags_default', '').strip()}` |")
w(f"| Java libraries | {' '.join('`' + d + '`' for d in env.get('deps', '').split())} |")
w(f"| Rust port | `{env.get('rust_version', '?')}` (sha256 {env.get('rust_sha256', '?')}…, "
  f"{int(env.get('rust_size', 0)) / 1048576:.2f} MiB static musl); in-process harness: {env.get('inproc', '?')} |")
w(f"| Tools | {env.get('hyperfine', '?')}, GNU time, poppler |")
w(f"| Fonts | {env.get('fonts', '?')} |")
w("")
w("Same inputs as `bench/run.sh`, static pages only. Rust gets pdfkit's exact invocation "
  "(`--quiet --page-size Letter --margin-* 0.75in --encoding UTF-8 - -`, HTML on stdin); "
  "Java parses the file with jsoup, converts it with `W3CDom`, injects "
  "`@page { size: 8.5in 11in; margin: 0.75in }` and registers the DejaVu TTFs (also as the "
  "`serif`/`sans-serif`/`monospace` generics), so both embed the same faces. "
  "Not compared: `js` (OpenHTMLtoPDF runs no JavaScript), `hf_toc` and `multi` "
  "(no `--header-html`/`--footer-html`, generated TOC or cover objects; CSS paged media "
  "would need hand-written equivalents, so it would not be the same input).")
w("")

# 1. Cold
w("## 1. Cold CLI: one process per conversion")
w("")
w("Wall time: hyperfine mean ± σ. CPU: hyperfine's mean user+sys per run. Peak RSS: median of "
  "the `/usr/bin/time -v` runs. CPU and RSS are robust to a busy host, wall time is not "
  "(see Caveats). Every command runs through `bash -c` (stdin/stdout redirections), the same "
  "few-ms shell overhead for every variant; hyperfine subtracts it.")
w("")
w("| Case | Variant | Wall mean ± σ | × Rust (wall) | CPU | × Rust (CPU) | Peak RSS | Output | Pages | Words |")
w("|---|---|---|---|---|---|---|---|---|---|")
for c, label in CASES:
    rust_wall = rust_cpu = None
    for v, vlabel in VARIANTS:
        base = os.path.join(OUT, "cold", f"{c}.{v}")
        meta = kv(base + ".meta")
        if not meta:
            continue
        if meta.get("rc") != "0":
            w(f"| {c} | {vlabel} | n/a (exit {meta.get('rc')}) | | | | | | | |")
            continue
        hf = jload(base + ".hyperfine.json")
        mean = sd = cpu = None
        if hf and hf.get("results"):
            r0 = hf["results"][0]
            mean = r0["mean"] * 1000
            sd = (r0.get("stddev") or 0) * 1000
            cpu = r0["user"] + r0["system"]
        tv = [t for t in (timev(p) for p in sorted(glob.glob(base + ".time*.txt"))) if t]
        rss = statistics.median(t["rss"] for t in tv) if tv else 0
        if v == "rust":
            rust_wall, rust_cpu = mean, cpu
        xw = f"{mean / rust_wall:.1f}×" if mean and rust_wall and v != "rust" else ""
        xc = f"{cpu / rust_cpu:.1f}×" if cpu and rust_cpu and v != "rust" else ""
        wall = f"{ms(mean)} ± {ms(sd)}" if mean is not None else "n/a"
        w(f"| {c} | {vlabel} | {wall} | {xw} | {ms(cpu * 1000)} | {xc} | {mib(rss)} | {size(meta.get('size', 0))} | "
          f"{meta.get('pages', '-')} | {meta.get('words', '-')} |" if cpu is not None else
          f"| {c} | {vlabel} | {wall} | {xw} | n/a | | n/a | {size(meta.get('size', 0))} | {meta.get('pages', '-')} | {meta.get('words', '-')} |")
w("")

# 2. Warm
w("## 2. Warm throughput: steady state")
w("")
w("- **Java**: one JVM converts the same document `loop_warmup` times untimed, then `loop` times "
  "timed (`Convert --warmup W --loop N`). ms/doc and CPU ms/doc cover the timed loop only "
  "(CPU = process CPU time, JIT and GC threads included); *first* is the first conversion in "
  "the JVM (class loading + interpreter, no JVM startup); peak RSS is the whole process.")
w("- **Rust in-process**: `wkhtmltopdf-inproc` calls `wkhtmltopdf_app::run` the same way "
  "(same warmup/loop counts, fresh stdin and output buffers per iteration).")
w("- **Rust CLI loop**: `loop` sequential processes; ms/doc = elapsed / N, CPU ms/doc = "
  "(user+sys) / N, RSS = largest single process. The CLI has no daemon, so this is its steady state.")
w(f"- Counts: `{env.get('mode', '')}`.")
w("- On a shared host, *min* is the least disturbed figure (interference only adds time); "
  "compare medians only on an idle machine.")
w("")
w("| Case | Implementation | ms/doc mean | median | min | p95 | CPU ms/doc | First | Peak RSS | Java / Rust in-process (median; min) |")
w("|---|---|---|---|---|---|---|---|---|---|")
for c, _ in CASES:
    rows = {}
    for impl, _ in WARM:
        base = os.path.join(OUT, "warm", f"{c}.{impl}")
        j = jload(base + ".json")
        t = timev(base + ".time.txt")
        if not j or not t or t["exit"] != 0:
            rows[impl] = None
            continue
        if impl == "rust-loop":
            n = j["loop"]
            j = {"mean_ms": t["elapsed"] * 1000 / n, "median_ms": None, "p95_ms": None, "min_ms": None,
                 "cpu_ms_per_doc": t["cpu"] * 1000 / n, "first_ms": None}
        rows[impl] = (j, t)
    for impl, ilabel in WARM:
        r = rows.get(impl)
        if r is None:
            w(f"| {c} | {ilabel} | n/a | | | | | | | |")
            continue
        j, t = r
        ratio = ""
        if impl == "java" and rows.get("rust-inproc"):
            ri = rows["rust-inproc"][0]
            ratio = f"{j['median_ms'] / ri['median_ms']:.1f}×; {j['min_ms'] / ri['min_ms']:.1f}×"
        cpu = j.get("cpu_ms_per_doc")
        w(f"| {c} | {ilabel} | {ms(j['mean_ms'])} | {ms(j.get('median_ms')) if j.get('median_ms') is not None else '-'} | "
          f"{ms(j.get('min_ms')) if j.get('min_ms') is not None else '-'} | "
          f"{ms(j.get('p95_ms')) if j.get('p95_ms') is not None else '-'} | "
          f"{ms(cpu) if cpu is not None and cpu >= 0 else 'n/a'} | "
          f"{ms(j.get('first_ms')) if j.get('first_ms') is not None else '-'} | {mib(t['rss'])} | {ratio} |")
w("")

# 3. Heap
w("## 3. Smallest Java heap")
w("")
w("`java -Xmx<M>m -jar convert.jar --warmup W --loop N` (`heap_warmup`/`heap_loop` above). "
  "*ok* means every conversion succeeded; the first size that fails with an "
  "`OutOfMemoryError` (or any error) is shown as *fail*.")
w("")
heap_cases = sorted({os.path.basename(p).split(".xmx")[0] for p in glob.glob(os.path.join(OUT, "heap", "*.rc"))},
                    key=lambda c: [x for x, _ in CASES].index(c) if c in [x for x, _ in CASES] else 99)
w("| Case | -Xmx | Result | ms/doc median | Peak RSS |")
w("|---|---|---|---|---|")
smallest = {}
for c in heap_cases:
    files = sorted(glob.glob(os.path.join(OUT, "heap", f"{c}.xmx*.rc")),
                   key=lambda p: int(re.search(r"xmx(\d+)", p).group(1)))
    for p in files:
        m = int(re.search(r"xmx(\d+)", p).group(1))
        rc = open(p).read().strip()
        base = p[:-3]
        t = timev(base + ".time.txt")
        j = jload(base + ".json")
        if rc == "0" and j:
            smallest.setdefault(c, m)
            w(f"| {c} | {m} MiB | ok | {ms(j['median_ms'])} | {mib(t['rss'] if t else 0)} |")
        else:
            err = ""
            try:
                txt = open(base + ".stderr").read()
                err = "OutOfMemoryError" if "OutOfMemoryError" in txt else f"exit {rc}"
            except OSError:
                err = f"exit {rc}"
            w(f"| {c} | {m} MiB | fail ({err}) | | {mib(t['rss'] if t else 0)} |")
w("")
for c in heap_cases:
    w(f"- `{c}`: smallest working heap among those tried: "
      f"{str(smallest[c]) + ' MiB' if c in smallest else 'none'}.")
w("")

# 4. Visual
w("## 4. Output sanity")
w("")
w("Page 1 of each engine's cold output at 60 dpi, side by side (left: wkhtmltopdf-rs, right: "
  "OpenHTMLtoPDF). Page counts differ by design: wkhtmltopdf lays out on a 96 dpi viewport and "
  "shrinks it to the printable width (smart shrinking), OpenHTMLtoPDF prints CSS sizes at "
  "their nominal size, so the same 11pt text takes more room. *Words* (in the cold table) is "
  "the `pdftotext` word count, a check that both outputs carry the whole text. "
  "`small.html` sets no font: the port's default face is DejaVu Sans (as QtWebKit's), "
  "OpenHTMLtoPDF's default family is serif, mapped here to DejaVu Serif. "
  "On `large`, OpenHTMLtoPDF does not repeat the `<thead>` on each page (it needs its "
  "proprietary `-fs-table-paginate: paginate`), hence 6 fewer words per continuation page.")
w("")
for c, label in CASES:
    png = os.path.join(OUT, "visual", f"{c}.png")
    if os.path.exists(png):
        r = kv(os.path.join(OUT, "cold", f"{c}.rust.meta"))
        j = kv(os.path.join(OUT, "cold", f"{c}.java.meta"))
        w(f"- [{label}](visual/{c}.png): fonts rust `{r.get('fonts', '?')}`, java `{j.get('fonts', '?')}`")
w("")

w("## Caveats")
w("")
w("- Wall-clock numbers depend on host load; this run's load average at start is in the "
  "Environment table. CPU time and peak RSS are far less sensitive. Rerun on an idle machine "
  "for wall-clock claims: `bench/java/run.sh --no-build`.")
w("- The JVM uses several threads (JIT compiler, GC): its CPU time can exceed its wall time, "
  "and on a loaded host it competes for cores the single-threaded Rust conversion does not need.")
w("- Layouts are not identical (see section 4), so per-document cost is not per-page cost: "
  "OpenHTMLtoPDF emits more pages for the same input.")
w("- `-Xshare:auto` is already the JVM default; the tuned variant differs from the default "
  "by `-XX:TieredStopAtLevel=1` (C1 only). The AppCDS variant adds an archive of the classes "
  "one conversion loads, built into the image (`/opt/bench/app.jsa`).")
w("- PDFBox logs font-fallback warnings while initialising its standard 14 fonts; stderr is "
  "discarded and the font cache (`~/.pdfbox.cache`) is prebuilt in the image, as it would be on "
  "a long-running server after its first start.")

with open(os.path.join(OUT, "REPORT.md"), "w") as f:
    f.write("\n".join(L) + "\n")
print(f"wrote {os.path.join(OUT, 'REPORT.md')}")
